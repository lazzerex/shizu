#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Command {
    MoveLeft { select: bool },
    MoveRight { select: bool },
    MoveUp { select: bool },
    MoveDown { select: bool },
    Home { select: bool },
    End { select: bool },
    PageUp { select: bool },
    PageDown { select: bool },
    Insert(char),
    Backspace,
    Delete,
    SelectAll,
    Cut,
    Copy,
    Paste,
    Undo,
    Redo,
    MoveLineUp,
    MoveLineDown,
    Save,
    Quit,
    Cancel,
    Click { column: u16, row: u16 },
    Drag { column: u16, row: u16 },
    ScrollLines(isize),
}
